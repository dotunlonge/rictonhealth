import leafletBundle from './leaflet-bundle.json';

export interface NearbyMapProvider {
  id: string;
  name: string;
  specialty?: string;
  latitude: number;
  longitude: number;
  distanceKm?: number;
}

export interface NearbyMapPayload {
  providers: NearbyMapProvider[];
  center?: [number, number];
  radiusKm?: number;
}

export interface NearbyMapMessage {
  type: 'select' | 'ready';
  id?: string;
}

/** Parses the WebView bridge message; returns null for anything unexpected. */
export function parseNearbyMapMessage(data: string): NearbyMapMessage | null {
  try {
    const parsed = JSON.parse(data) as Partial<NearbyMapMessage>;
    if (parsed && (parsed.type === 'select' || parsed.type === 'ready')) {
      return { type: parsed.type, id: parsed.id };
    }
  } catch {
    return null;
  }
  return null;
}

export const OSM_TILE_URL = 'https://tile.openstreetmap.org/{z}/{x}/{y}.png';

const PAGE_STYLES = [
  'html,body,#map{height:100%;margin:0;padding:0;}',
  '.leaflet-container{font-family:inherit;}',
  '.ricton-popup-btn{margin-top:6px;border:0;border-radius:9999px;background:#1877F2;color:#fff;',
  'font-weight:700;font-size:12px;padding:6px 12px;cursor:pointer;}',
].join('\n');

/**
 * Builds the self-contained HTML document for the nearby-doctor map.
 *
 * Leaflet and its CSS are vendored into `leaflet-bundle.json` (generated by
 * `scripts/build-mobile-nearby-map.ts`), so the WebView needs no CDN and no
 * API key. The only runtime network call is the OpenStreetMap tile server.
 */
export function buildNearbyMapHtml(): string {
  return [
    '<!DOCTYPE html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8" />',
    '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no" />',
    '<style>',
    leafletBundle.css,
    PAGE_STYLES,
    '</style>',
    '</head>',
    '<body>',
    '<div id="map"></div>',
    '<script>',
    leafletBundle.js,
    '</script>',
    '<script>',
    leafletBundle.init,
    '</script>',
    '</body>',
    '</html>',
  ].join('\n');
}
